#!/usr/bin/env node
/*
 * Regenerates testdata/merkle-proof-golden.json — the cross-language fixture for
 * SPV-style inclusion proofs.
 *
 * The reference implementation is the backend's anchoring tree (merkletreejs with
 * keccak256 and sortPairs: true). The Go CLI's `ernest proof verify` must accept
 * every proof in this file and reject the tampered variants; its golden test reads
 * the same JSON. As with the hash vectors: never change existing expected values —
 * receipts already issued under the old construction would stop verifying.
 *
 * Usage: node scripts/generate-merkle-proof-vector.cjs
 */
const { createHash } = require('crypto');
const { writeFileSync } = require('fs');
const path = require('path');
const base = path.join(__dirname, '..', 'backend', 'node_modules');
const { MerkleTree } = require(path.join(base, 'merkletreejs'));
const keccak256 = require(path.join(base, 'keccak256'));

// Deterministic synthetic block hashes: sha256("ernest-block-<i>").
function blockHash(i) {
  return createHash('sha256').update(`ernest-block-${i}`).digest('hex');
}

function buildCase(name, comment, leafCount, proofIndexes) {
  const hashes = Array.from({ length: leafCount }, (_, i) => blockHash(i));
  const leaves = hashes.map((h) => Buffer.from(h, 'hex'));
  const tree = new MerkleTree(leaves, keccak256, { sortPairs: true });
  const root = '0x' + tree.getRoot().toString('hex');
  return {
    name,
    comment,
    blockHashes: hashes,
    merkleRoot: root,
    proofs: proofIndexes.map((index) => ({
      blockIndex: index,
      blockHash: hashes[index],
      proof: tree.getProof(leaves[index]).map((p) => '0x' + p.data.toString('hex')),
    })),
  };
}

const out = {
  $comment:
    'Cross-language golden fixture for Merkle inclusion proofs. Construction: merkletreejs over block-hash leaves (hex-decoded), keccak256, sortPairs: true; odd nodes promote unchanged. Verification walks the proof hashing keccak256(sort(current, sibling)) and compares to merkleRoot. Generated by scripts/generate-merkle-proof-vector.cjs from the backend implementation; consumed by cli-ernest/cmd/proof golden tests. Never change existing expected values: issued receipts would stop verifying.',
  hashAlgorithm: 'keccak256',
  pairSorting: 'sorted',
  cases: [
    buildCase('single-leaf', 'One-block chain: root equals the leaf, proof is empty.', 1, [0]),
    buildCase('two-leaves', 'Smallest real tree.', 2, [0, 1]),
    buildCase('seven-leaves', 'Odd leaf count exercises unpaired-node promotion at multiple levels.', 7, [0, 3, 6]),
    buildCase('fifty-leaves', 'ANCHOR_EVERY_N_BLOCKS-sized tree, first/middle/last.', 50, [0, 25, 49]),
  ],
};

const target = path.join(__dirname, '..', 'testdata', 'merkle-proof-golden.json');
writeFileSync(target, JSON.stringify(out, null, 2) + '\n');
console.log(`Wrote ${out.cases.length} cases to ${target}`);
for (const c of out.cases) console.log(`  ${c.name}: root ${c.merkleRoot}`);
